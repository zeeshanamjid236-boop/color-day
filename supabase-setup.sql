-- Run this once in Supabase > SQL Editor > New query
create table if not exists public.color_day_wishes (
  id bigint generated by default as identity primary key,
  student_name text not null check (char_length(student_name) between 1 and 35),
  wish text not null check (char_length(wish) between 1 and 180),
  created_at timestamptz not null default now()
);

alter table public.color_day_wishes enable row level security;

drop policy if exists "Public can read Color Day wishes" on public.color_day_wishes;
create policy "Public can read Color Day wishes"
on public.color_day_wishes for select to anon
using (true);

drop policy if exists "Public can add Color Day wishes" on public.color_day_wishes;
create policy "Public can add Color Day wishes"
on public.color_day_wishes for insert to anon
with check (
  char_length(student_name) between 1 and 35
  and char_length(wish) between 1 and 180
);
